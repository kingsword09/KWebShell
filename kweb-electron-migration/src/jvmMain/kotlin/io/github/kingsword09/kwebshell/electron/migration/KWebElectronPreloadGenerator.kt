            appendLine("    };")
        }
        appendLine("  }")
        appendLine("}")
        appendLine("export {};")
    }.trimEnd() + "\n"

    private fun generateJavaScript(
        manifest: KWebElectronManifest,
        methods: List<KWebElectronPreloadMethod>,
        streams: List<KWebElectronStream>,
    ): String = buildString {
        val appPathMethods = methods.filter { it.adapter == KWebElectronAdapterKind.APP_PATHS_GET_PATH }
        val filesMethods = methods.filter { it.adapter == KWebElectronAdapterKind.FILES_OPERATION }
        val filesStreams = streams.filter { it.adapter == KWebElectronAdapterKind.FILES_WATCH_DIRECTORY }
        val clipboardMethods = methods.filter { it.adapter == KWebElectronAdapterKind.CLIPBOARD_OPERATION }
        val applicationStreams = streams.filter { it.adapter == KWebElectronAdapterKind.NAMED_APPLICATION_STREAM }
        appendLine("// Generated by KWebShell Electron migration codegen. Do not edit.")
        appendLine("(() => {")
        appendLine("  \"use strict\";")
        if (appPathMethods.isNotEmpty()) {
            appendLine("  const bridge = globalThis.KWebAppPathsBridge;")
            appendLine("  if (!bridge || typeof bridge.createClient !== \"function\") {")
            appendLine("    throw new Error(\"KWebAppPathsBridge is required by this migration facade.\");")
            appendLine("  }")
        }
        if (filesMethods.isNotEmpty() || filesStreams.isNotEmpty()) {
            appendLine("  const filesBridge = globalThis.FilesBridge;")
            appendLine("  if (!filesBridge || typeof filesBridge.createClient !== \"function\") {")
            appendLine("    throw new Error(\"FilesBridge is required by this migration facade.\");")
            appendLine("  }")
        }
        appendLine("  class KWebElectronMigrationError extends Error {")
        appendLine("    constructor(code, message) {")
        appendLine("      super(message);")
        appendLine("      this.name = \"KWebElectronMigrationError\";")
        appendLine("      this.code = code;")
        appendLine("    }")
        appendLine("  }")
        if (appPathMethods.isNotEmpty()) {
            appendLine("  const pathKinds = Object.freeze({")
            electronPathKinds().forEach { (name, kind) -> appendLine("    ${name}: \"${kind}\",") }
            appendLine("  });")
            appendLine("  const client = bridge.createClient();")
        }
        if (filesMethods.isNotEmpty() || filesStreams.isNotEmpty()) appendLine("  const filesClient = filesBridge.createClient();")
        if (clipboardMethods.isNotEmpty()) {
            appendLine("  const clipboardBridge = globalThis.ClipboardBridge;")
            appendLine("  if (!clipboardBridge || typeof clipboardBridge.createClient !== \"function\") throw new Error(\"ClipboardBridge is required by this migration facade.\");")
            appendLine("  const clipboardClient = clipboardBridge.createClient();")
        }
        if (applicationStreams.isNotEmpty()) {
            appendLine("  const streamBridge = globalThis.KWebApplicationStreamsBridge;")
            appendLine("  if (!streamBridge || typeof streamBridge.createClient !== \"function\") throw new Error(\"KWebApplicationStreamsBridge is required by this migration facade.\");")
            appendLine("  const bridgeStreams = streamBridge.createClient();")
        } else {
            appendLine("  const bridgeStreams = null;")
        }
        appendLine("  const api = Object.freeze({")
        methods.forEach { method ->
            when (method.adapter) {
                KWebElectronAdapterKind.APP_PATHS_GET_PATH -> {
                    appendLine("    ${method.name}: (name, options) => {")
                    appendLine("      const kind = pathKinds[name];")
                    appendLine("      if (typeof kind !== \"string\") {")
                    appendLine("        return Promise.reject(new KWebElectronMigrationError(\"migration.path-name.unsupported\", \"The Electron path name is not published by KWebShell.\"));")
                    appendLine("      }")
                    appendLine("      return client.resolve({ kind }, options).then(result => result.path);")
                    appendLine("    },")
                }
                KWebElectronAdapterKind.FILES_OPERATION -> {
                    appendLine("    ${method.name}: (request, options) => filesClient.${operationFor(manifest, method)}(request, options),")
                }
                KWebElectronAdapterKind.CLIPBOARD_OPERATION -> {
                    appendLine("    ${method.name}: (request, options) => clipboardClient.${operationFor(manifest, method)}(request, options),")
                }
                KWebElectronAdapterKind.FILES_WATCH_DIRECTORY -> error("files watch adapters are generated from manifest streams")
                KWebElectronAdapterKind.NAMED_APPLICATION_STREAM -> error("stream adapters are generated from manifest streams")
                null -> error("validated adapters cannot be null")
            }
        }
        streams.forEach { stream ->
            val receiver = if (stream.adapter == KWebElectronAdapterKind.FILES_WATCH_DIRECTORY) "filesClient" else "bridgeStreams"
            appendLine("    ${stream.name}: (request, options) => $receiver.open${stream.method.replaceFirstChar { it.uppercaseChar() }}(request, options),")
        }
        appendLine("  });")
        appendLine("  Object.defineProperty(globalThis, \"${manifest.rendererGlobal}\", {")
        appendLine("    configurable: false,")
        appendLine("    enumerable: true,")
        appendLine("    writable: false,")
        appendLine("    value: api,")
        appendLine("  });")
        appendLine("})();")
    }

    private fun StringBuilder.appendStreamTypes(streams: List<KWebElectronStream>) {
        if (streams.isEmpty()) return
        appendLine()
        streams.forEach { stream ->
            if (stream.adapter != KWebElectronAdapterKind.FILES_WATCH_DIRECTORY) {
                appendLine("export type ${stream.requestType} = Record<string, unknown>;")
                appendLine("export type ${stream.chunkType} = Record<string, unknown>;")
            }
        }
        appendLine("export interface KWebElectronStreamOptions {")
        appendLine("  readonly signal?: AbortSignal;")
        appendLine("}")
        appendLine("export interface KWebElectronStream<Chunk> extends AsyncIterable<Chunk> {")
        appendLine("  close(): void;")
        appendLine("}")
    }

    private fun StringBuilder.appendFilesTypes(
        manifest: KWebElectronManifest,
        methods: List<KWebElectronPreloadMethod>,
        streams: List<KWebElectronStream>,
    ) {
        val definitions = linkedMapOf<String, List<String>>()
        methods.forEach { method ->
            val operation = manifest.channels.single { it.name == method.channel }.operationId
                ?: error("A validated files adapter must declare an operation.")
            val requestFields = when (operation) {
                "open-workspace" -> listOf("workspaceId: string", "grants: readonly string[]")
                "open-file" -> listOf("parent: string", "name: string", "mode: string", "createIfMissing: boolean")
                "write-file" -> listOf("handle: string", "offset: string", "bytes: readonly number[]")
                "read-file" -> listOf("handle: string", "offset: string", "length: number")
                "list-directory" -> listOf("handle: string", "limit: number")
                "close-handle" -> listOf("handle: string")
                else -> emptyList()
            }
            if (requestFields.isNotEmpty()) definitions[method.parameterType] = requestFields
            val responseType = manifest.channels.single { it.name == method.channel }.responseType
            val responseFields = when (operation) {
                "open-workspace", "open-file" -> listOf("handle: string", "kind: string", "name: string", "grants: readonly string[]")
                "write-file" -> listOf("written: number")
                "read-file" -> listOf("bytes: readonly number[]", "eof: boolean")
                "list-directory" -> listOf("entries: readonly FilesDirectoryEntry[]", "truncated: boolean")
                "close-handle" -> listOf("closed: boolean")
                else -> emptyList()
            }
            if (responseFields.isNotEmpty()) definitions[responseType] = responseFields
        }
        if (methods.any { manifest.channels.single { channel -> channel.name == it.channel }.operationId == "list-directory" }) {
            definitions.putIfAbsent(
                "FilesDirectoryEntry",
                listOf("name: string", "kind: string", "sizeBytes: string | null", "lastModifiedEpochMillis: string"),
            )
        }
        streams.filter { it.adapter == KWebElectronAdapterKind.FILES_WATCH_DIRECTORY }.forEach { stream ->
            definitions[stream.requestType] = listOf("handle: string")
            definitions[stream.chunkType] = listOf("sequence: string", "kind: string", "name: string | null")
        }
        definitions.forEach { (type, fields) ->
            appendLine("export interface $type {")
            fields.forEach { field -> appendLine("  $field;") }
            appendLine("}")
        }
    }

    private fun StringBuilder.appendClipboardTypes(
        methods: List<KWebElectronPreloadMethod>,
    ) {
        if (methods.isEmpty()) return
        appendLine("export interface ClipboardPayloadDescriptor {")
        appendLine("  handle: string; format: string; encoding: string; sizeBytes: string;")
        appendLine("}")
        appendLine("export interface ClipboardReadRequest { selection: string; formats: readonly string[]; }")
        appendLine("export interface ClipboardReadResponse { sequence: string; available: readonly ClipboardPayloadDescriptor[]; }")
        appendLine("export interface ClipboardReadPayloadRequest { handle: string; offset: string; length: number; }")
        appendLine("export interface ClipboardReadPayloadResponse { bytes: readonly number[]; eof: boolean; }")
        appendLine("export interface ClipboardWriteItem { format: string; encoding: string; bytes: readonly number[]; }")
        appendLine("export interface ClipboardWriteRequest { selection: string; items: readonly ClipboardWriteItem[]; }")
        appendLine("export interface ClipboardClearRequest { selection: string; }")
        appendLine("export interface ClipboardWriteResponse { sequence: string; }")
        appendLine("export interface ClipboardClearResponse { sequence: string; }")
        appendLine("export interface ClipboardClosePayloadRequest { handle: string; }")
        appendLine("export interface ClipboardClosePayloadResponse { closed: boolean; }")
    }

    private fun apiTypeName(manifest: KWebElectronManifest): String =
        manifest.rendererGlobal.replaceFirstChar { it.uppercaseChar() } + "Api"

    private fun operationFor(
        manifest: KWebElectronManifest,
        method: KWebElectronPreloadMethod,
    ): String = manifest.channels.single { it.name == method.channel }.operationId
        ?.split('-')
        ?.mapIndexed { index, part -> if (index == 0) part else part.replaceFirstChar { it.uppercaseChar() } }
        ?.joinToString("")
        ?: error("A validated files adapter must declare an operation.")

    private fun pathTypeUnion(): String = electronPathKinds().keys.joinToString(" | ") { "\"$it\"" }

